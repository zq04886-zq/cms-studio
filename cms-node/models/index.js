const { PrismaClient } = require('@prisma/client')
const { PrismaMariaDb } = require('@prisma/adapter-mariadb')
const { db } = require('../config')
const adapter = new PrismaMariaDb({ host: db.host, port: db.port, user: db.username, password: db.password, database: db.database, connectionLimit: 5, connectTimeout: 10000, timezone: '+00:00' })
module.exports = new PrismaClient({ adapter })
